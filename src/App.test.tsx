// @vitest-environment jsdom
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { render, screen } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import App from './App'

describe('rare disease coordination office', () => {
  it('loads network cases from the Java API', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue({
      ok: true,
      json: async () => [{ id: 1, title: 'Rare neuromuscular expert consultation', owner: 'European Reference Network Team', status: 'Review', priority: 'High' }],
    }))
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
    render(<QueryClientProvider client={client}><App /></QueryClientProvider>)
    expect(await screen.findByText('Rare neuromuscular expert consultation')).toBeTruthy()
    expect(screen.getByRole('heading', { name: 'Rare Disease Network Office' })).toBeTruthy()
  })
})
